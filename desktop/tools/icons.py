#!/usr/bin/env python3
"""Builds src/ui/icon_map.rs from Material Symbols Rounded (Apache-2.0).
Run after adding names to NAMES. Source font: the ttf-material-symbols-variable package."""
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

SRC = "/usr/share/fonts/TTF/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf"
NAMES = """home search library_music settings favorite play_arrow pause skip_previous skip_next shuffle repeat repeat_one
lyrics queue_music more_horiz more_vert volume_up volume_down volume_off volume_mute arrow_back chevron_right chevron_left expand_more expand_less
close add check download download_done file_download_off share link content_copy edit delete push_pin sensors person album
mic history playlist_add playlist_play bar_chart language translate palette high_quality all_inclusive restore public shield
security cloud_off manage_search search_off delete_sweep insights cloud_upload storage cleaning_services delete_forever
volunteer_activism bug_report info lightbulb mail upload_file folder_open table_view explore music_note graphic_eq data_saver_on
bedtime drag_indicator visibility visibility_off star sync thumb_up thumb_down account_circle smartphone import_export tune
timer new_releases trending_up open_in_full close_fullscreen key queue_play_next library_add library_add_check format_quote
cancel login lock radio subscriptions settings_backup_restore phone_iphone mobile swap_vert fiber_new phonelink devices backup sync_alt
refresh arrow_upward arrow_downward menu format_list_bulleted image image_search speaker system_update hide_image headphones add_photo_alternate open_in_new equalizer""".split()

f = TTFont(SRC)
codes = {}
for cp, g in sorted(f.getBestCmap().items()):
    if g in NAMES and g not in codes: codes[g] = cp
for n in NAMES:
    if n not in codes: print("missing", n, file=sys.stderr)
# Each icon becomes an SVG path (crisp at any size / interface scale — no font hinting or smoothing artefacts).
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
def paths(fill):
    inst = instancer.instantiateVariableFont(TTFont(SRC), {"wght": 400, "GRAD": 0, "opsz": 24, "FILL": fill})
    gs = inst.getGlyphSet(); cm = inst.getBestCmap(); upm = inst["head"].unitsPerEm; asc = inst["hhea"].ascent
    out = {}
    for n, cp in codes.items():
        pen = SVGPathPen(gs); gs[cm[cp]].draw(TransformPen(pen, (1, 0, 0, -1, 0, asc)))
        out[n] = pen.getCommands()
    return out, upm, asc - upm
outline, upm, top = paths(0); filled, _, _ = paths(1)
with open("src/ui/icon_map.rs", "w") as o:
    o.write("// Generated by tools/icons.py from Material Symbols Rounded (Apache-2.0): SVG paths in a %d-unit box.\n" % upm)
    o.write("pub const VIEWBOX: &str = \"0 %d %d %d\";\n" % (top, upm, upm))
    o.write("pub fn path(name: &str, fill: bool) -> &'static str {\n    match (name, fill) {\n")
    for n in sorted(codes):
        o.write('        ("%s", false) => "%s",\n' % (n, outline[n]))
        if filled[n] != outline[n]: o.write('        ("%s", true) => "%s",\n' % (n, filled[n]))
    o.write("        (n, true) => path(n, false),\n        _ => \"\",\n    }\n}\n")
print(len(codes), "icons")
